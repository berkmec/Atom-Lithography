def new_canvas(title: str, subtitle: str):
    surf = cairo.ImageSurface(cairo.FORMAT_ARGB32, W, H)
    ctx = cairo.Context(surf)
    ctx.set_antialias(cairo.ANTIALIAS_BEST)
    ctx.set_source_rgb(*C_BG)
    ctx.rectangle(0, 0, W, H)
    ctx.fill()

    # Title banner
    ctx.set_source_rgb(*C_HEADER)
    ctx.rectangle(0, 0, W, 92)
    ctx.fill()

    ctx.select_font_face("DejaVu Sans", cairo.FONT_SLANT_NORMAL, cairo.FONT_WEIGHT_BOLD)
    ctx.set_font_size(27)
    ctx.set_source_rgb(1.0, 1.0, 1.0)
    ctx.move_to(36, 42)
    ctx.show_text(title)

    ctx.select_font_face("DejaVu Sans", cairo.FONT_SLANT_NORMAL, cairo.FONT_WEIGHT_NORMAL)
    ctx.set_font_size(16)
    ctx.set_source_rgb(0.80, 0.87, 0.96)
    ctx.move_to(36, 72)
    ctx.show_text(subtitle)

    # Footer
    ctx.set_source_rgb(*C_MUTED)
    ctx.set_font_size(13)
    ctx.move_to(36, H - 18)
    ctx.show_text(
        "Atom Lithography Machine (v2.24 / Exp127) | Epistemic Tag: {Model} & {Aday-COTS} | "
        "no_lab_measurement=true | Generated by src/board/detector_frontend.py & experiments/exp127_detector_frontend_sim/"
    )
    return surf, ctx


def save_surface(surf: cairo.ImageSurface, path: Path) -> None:
    surf.flush()
    # Cairo ARGB32 -> RGBA via PIL for crisp lossless PNG
    buf = surf.get_data()
    img = Image.frombuffer("RGBA", (W, H), bytes(buf), "raw", "BGRA", 0, 1)
    img.convert("RGB").save(path, "PNG", optimize=True)
    print(f"SAVED {path} ({W}x{H})")


def draw_text(ctx, x, y, text, size=15, bold=False, color=C_TEXT, align="left"):
    ctx.select_font_face(
        "DejaVu Sans",
        cairo.FONT_SLANT_NORMAL,
        cairo.FONT_WEIGHT_BOLD if bold else cairo.FONT_WEIGHT_NORMAL,
    )
    ctx.set_font_size(size)
    ext = ctx.text_extents(text)
    if align == "center":
        x -= ext.width / 2.0 + ext.x_bearing
    elif align == "right":
        x -= ext.width + ext.x_bearing
    ctx.set_source_rgb(*color)
    ctx.move_to(x, y)
    ctx.show_text(text)


def draw_rotated_text(ctx, x, y, text, angle_deg=-90, size=15, bold=True, color=C_TEXT):
    ctx.save()
    ctx.translate(x, y)
    ctx.rotate(math.radians(angle_deg))
    draw_text(ctx, 0, 0, text, size=size, bold=bold, color=color, align="center")
    ctx.restore()


def draw_panel(ctx, x, y, w, h, title: str):
    ctx.set_source_rgb(*C_PANEL)
    ctx.rectangle(x, y, w, h)
    ctx.fill()
    ctx.set_source_rgb(0.76, 0.80, 0.86)
    ctx.set_line_width(1.5)
    ctx.rectangle(x, y, w, h)
    ctx.stroke()
    draw_text(ctx, x + 18, y + 32, title, size=19, bold=True, color=C_HEADER)


def draw_polyline(ctx, pts, color, width=2.8, dash=None):
    if len(pts) < 2:
        return
    ctx.save()
    ctx.set_source_rgb(*color)
    ctx.set_line_width(width)
    if dash:
        ctx.set_dash(dash)
    ctx.move_to(pts[0][0], pts[0][1])
    for px, py in pts[1:]:
        ctx.line_to(px, py)
    ctx.stroke()
    ctx.restore()


def draw_markers(ctx, pts, color, radius=4.5):
    ctx.save()
    ctx.set_source_rgb(*color)
    for px, py in pts:
        ctx.arc(px, py, radius, 0, 2.0 * math.pi)
        ctx.fill()
    ctx.restore()


