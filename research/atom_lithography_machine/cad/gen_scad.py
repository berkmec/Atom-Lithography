"""Generate 8 parametric OpenSCAD files (7 subsystems in parts/ + master assembly).

Single source of truth: `params.py`. Do not hand-edit emitted `.scad` files.
"""
from __future__ import annotations

from pathlib import Path

import params

CAD_DIR = Path(__file__).resolve().parent
PARTS_DIR = CAD_DIR / "parts"


def _hex_to_rgb(h: str) -> tuple[float, float, float]:
    h = h.lstrip("#")
    return tuple(round(int(h[i : i + 2], 16) / 255.0, 3) for i in (0, 2, 4))


def _axis_rot(axis: str) -> str:
    if axis == "z":
        return ""
    if axis == "x":
        return "rotate([0, 90, 0]) "
    if axis == "y":
        return "rotate([-90, 0, 0]) "
    raise ValueError(axis)


def _emit_solid_scad(name: str, spec: dict, indent: str = "  ") -> list[str]:
    r, g, b = _hex_to_rgb(params.part_color(spec))
    cx, cy, cz = spec["center"]
    sh = spec["shape"]
    d = spec["dims"]
    alpha = spec["alpha"]
    out = [
        f'{indent}// {name} [{spec["bom_id"]}] {spec["label_tr"]} ({spec["material"]}, ±{spec["tol_mm"]} mm)',
        f'{indent}color([{r}, {g}, {b}], {alpha}) translate([{cx}, {cy}, {cz}])',
    ]
    if sh == "box":
        out.append(f"{indent}  cube([{d[0]}, {d[1]}, {d[2]}], center=true);")
    elif sh == "cyl":
        rot = _axis_rot(d[2])
        out.append(f"{indent}  {rot}cylinder(r={d[0]}, h={d[1]}, center=true);")
    elif sh == "tube":
        rot = _axis_rot(d[3])
        out.append(f"{indent}  {rot}difference() {{")
        out.append(f"{indent}    cylinder(r={d[1]}, h={d[2]}, center=true);")
        out.append(f"{indent}    cylinder(r={d[0]}, h={d[2] + 0.4}, center=true);")
        out.append(f"{indent}  }}")
    elif sh == "arc_tube":
        ri, ro, h, deg0, deg1 = d
        span = deg1 - deg0
        out.append(
            f"{indent}  rotate([0, 0, {deg0}]) rotate_extrude(angle={span}) "
            f"translate([{ri}, {-h / 2.0}]) square([{ro - ri}, {h}]);"
        )
    elif sh == "frustum":
        out.append(f"{indent}  cylinder(r1={d[0]}, r2={d[1]}, h={d[2]}, center=true);")
    elif sh == "frame":
        ox, oy, ix, iy, h = d
        out.append(f"{indent}  difference() {{")
        out.append(f"{indent}    cube([{ox}, {oy}, {h}], center=true);")
        out.append(f"{indent}    cube([{ix}, {iy}, {h + 0.4}], center=true);")
        out.append(f"{indent}  }}")
    else:
        raise ValueError(f"Unsupported shape: {sh}")
    return out


def emit_subsystem_scad(sub_key: str) -> str:
    meta = params.SUBSYSTEMS[sub_key]
    sub_parts = params.subsystem_parts(sub_key)
    lines = [
        f"// Atom Lithography Machine ({params.CAD_VERSION}) — {meta['code']}: {meta['title_tr']}",
        f"// Drawing No: {meta['drawing_no']} | Units: {params.UNITS} | Tol: {params.GENERAL_TOLERANCE_STD}",
        "// Generated by gen_scad.py from params.py — DO NOT EDIT DIRECTLY.",
        "$fn = 48;",
        "",
        f"module {sub_key}() {{",
    ]
    for pname, spec in sub_parts.items():
        lines.extend(_emit_solid_scad(pname, spec, indent="  "))
    lines.extend([
        "}",
        "",
        "// Standalone preview (comment out when `use <...>` imported)",
        f"{sub_key}();",
        "",
    ])
    return "\n".join(lines)


def emit_master_scad() -> str:
    b0, b1 = params.BEAM
    bz = 0.5 * (b0[2] + b1[2])
    bh = abs(b0[2] - b1[2])
    lines = [
        f"// Atom Lithography Machine ({params.CAD_VERSION}) — Master Assembly",
        f"// Scale: s={params.GOLDEN_SCALE_S} (Exp80) | Units: {params.UNITS} | Tol: {params.GENERAL_TOLERANCE_STD}",
        "// Generated by gen_scad.py from params.py — DO NOT EDIT DIRECTLY.",
        "$fn = 48;",
        "cutaway = false;  // set true for Y<0 half-section view",
        "explode = 0.0;    // 0.0 = assembled, 1.0 = full exploded view",
        "",
    ]
    for sub_key in params.SUBSYSTEMS:
        lines.append(f"use <parts/{sub_key}.scad>;")
    lines.extend(["", "module atom_litho_machine_assembled() {"])
    for sub_key, meta in params.SUBSYSTEMS.items():
        ex, ey, ez = meta["explode_vec"]
        lines.append(f"  // {meta['code']}: {meta['title_tr']}")
        lines.append(f"  translate([explode * {ex}, explode * {ey}, explode * {ez}]) {sub_key}();")
    lines.extend([
        "  // Ion beam axis marker (visual only, 10->5 keV)",
        f'  color([1.0, 0.85, 0.0], 0.85) translate([{b0[0]}, {b0[1]}, {bz}])',
        f"    cylinder(r=2.0, h={bh}, center=true);",
        "}",
        "",
        "if (cutaway) {",
        "  difference() {",
        "    atom_litho_machine_assembled();",
        "    translate([-1200, -1000, -50]) cube([2800, 1000, 1700]);",
        "  }",
        "} else {",
        "  atom_litho_machine_assembled();",
        "}",
        "",
    ])
    return "\n".join(lines)


def main() -> None:
    PARTS_DIR.mkdir(parents=True, exist_ok=True)
    for sub_key in params.SUBSYSTEMS:
        out_path = PARTS_DIR / f"{sub_key}.scad"
        out_path.write_text(emit_subsystem_scad(sub_key), encoding="utf-8")
        print("SCAD_PART", out_path.name, "parts:", len(params.subsystem_parts(sub_key)))
    master_path = CAD_DIR / "atom_litho_machine.scad"
    master_path.write_text(emit_master_scad(), encoding="utf-8")
    print("SCAD_MASTER", master_path.name, "total_parts:", len(params.PARTS))


if __name__ == "__main__":
    main()
